        // Flattens the week rows above into the { date, weight } entries the
        // rest of the app speaks.
        function expandHistorySeed() {
            const out = [];
            WEIGHT_HISTORY_SEED.forEach((row) => {
                const monday = parseDayKey(row[0]);
                row[1].forEach((w, i) => {
                    if (w === null || w === undefined) return;
                    const day = new Date(monday);
                    day.setDate(day.getDate() + i);
                    out.push({ date: localDayKey(day), weight: w, imported: true });
                });
            });
            return out;
        }
